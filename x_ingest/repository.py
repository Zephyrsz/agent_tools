"""Persistence seam shared by crawl workflows and projections."""

from __future__ import annotations

from typing import Any, Iterable, Protocol

from .models import Post


class PostRepository(Protocol):
    def initialize(self) -> None: ...
    def close(self) -> None: ...

    def begin_crawl(self, handle: str, *, mode: str = "incremental",
                    requested_from: str | None = None,
                    requested_until: str | None = None,
                    started_at: str | None = None) -> int: ...

    def finish_crawl(self, run_id: int, **counts: Any) -> None: ...

    def upsert_posts(self, posts: Iterable[Post | dict[str, Any]], *, handle: str,
                     captured_at: str | None = None,
                     relation: str = "own_post") -> dict[str, int]: ...

    def get_state(self, handle: str) -> dict[str, Any] | None: ...
    def query_posts(self, **filters: Any) -> list[dict[str, Any]]: ...
    def get_media(self, post_id: str) -> list[dict[str, Any]]: ...
    def set_obsidian_path(self, post_id: str, path: str | None) -> None: ...
